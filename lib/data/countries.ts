// Lookup maps for O(1) access
export const COUNTRY_BY_CODE = Object.fromEntries(COUNTRIES.map(c => [c.code, c]))
export const COUNTRY_BY_NAME = Object.fromEntries(COUNTRIES.map(c => [c.name.toLowerCase(), c]))

export function getCountryByCode(code: string): Country | undefined {
  return COUNTRY_BY_CODE[code?.toUpperCase()]
}

export function getCountryByName(name: string): Country | undefined {
  return COUNTRY_BY_NAME[name?.toLowerCase()]
}
